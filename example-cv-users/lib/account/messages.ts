export function translate(text: string, locale: UiLocale): string {
  if (!text || locale === 'zh') return text;
  return english[text] ?? english[messages.unavailable];
}
export function codeOf(text: string): MessageCode {
  return (Object.keys(messages) as MessageCode[]).find(key => messages[key] === text) ?? 'unavailable';
}
