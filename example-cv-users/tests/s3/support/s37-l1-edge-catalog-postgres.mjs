import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, realpathSync, rmSync } from 'node:fs';
import { isAbsolute, join } from 'node:path';
import test from 'node:test';

import { checkL1EdgeCatalogWitness } from '../../../scripts/s37-hosted/l1-edge-catalog-witness.mjs';

const pgBin = process.env.S37_TEST_PG17_BIN;
assert.ok(isAbsolute(pgBin ?? ''), 'Provide the absolute path to PostgreSQL fixture binaries');
const pg = (binary, args, input) => execFileSync(join(pgBin, binary), args, {
  input, encoding: 'utf8', timeout: 20_000, env: { LC_ALL: 'C', PATH: '/usr/bin:/bin' },
});
assert.match(pg('postgres', ['--version']), /\b17\.12\b/);
const sha = value => createHash('sha256').update(value).digest('hex');

// The query runs only in the throwaway fixture below. The observed XIDs,
// privileges, closure, and digests are generated by PostgreSQL itself.
const observe = `
BEGIN READ ONLY;
WITH l1 AS (
  SELECT oid, xmin::text AS xid FROM pg_namespace WHERE nspname = 'fixture_l1'
), ix AS (
  SELECT xmin::text AS xid, indisvalid, indisunique, indpred IS NOT NULL AS partial
  FROM pg_index WHERE indexrelid = 'fixture_l1.only_open'::regclass
), c AS (
  SELECT xmin::text AS xid, convalidated FROM pg_constraint
  WHERE conname = 'owner_once' AND conrelid = 'fixture_l1.owners'::regclass
), edge_ns AS (
  SELECT oid, xmin::text AS xid, nspowner::regrole::text AS owner FROM pg_namespace WHERE nspname = 'fixture_edge'
), edge_rel AS (
  SELECT t.xmin::text AS xid, t.relrowsecurity, t.relforcerowsecurity FROM pg_class t JOIN edge_ns e ON e.oid = t.relnamespace
  WHERE t.relname = 'files'
), edge_fn AS (
  SELECT p.oid, p.xmin::text AS xid FROM pg_proc p JOIN edge_ns e ON e.oid = p.pronamespace WHERE p.proname = 'read_file'
)
SELECT jsonb_build_object(
  'identity', jsonb_build_object(
    'project', 'fixture_project', 'database', current_database(), 'observer', current_user,
    'readonly', current_setting('transaction_read_only'), 'version', current_setting('server_version_num'),
    'server', encode(sha256(convert_to(coalesce(inet_server_addr()::text, 'unix'), 'UTF8')), 'hex'),
    'system', encode(sha256(convert_to((SELECT system_identifier::text FROM pg_control_system()), 'UTF8')), 'hex'),
    'started', to_char(pg_postmaster_start_time() AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"'),
    'l1Xid', (SELECT xid FROM l1), 'l1Status', (SELECT pg_xact_status(xid::xid8) FROM l1),
    'forwardIndexXid', (SELECT xid FROM ix WHERE indisvalid AND indisunique AND partial),
    'forwardConstraintXid', (SELECT xid FROM c WHERE convalidated),
    'forwardStatus', (SELECT pg_xact_status(xid::xid8) FROM ix)),
  'closure', jsonb_build_object(
    'closed', (SELECT payload FROM fixture_l1.state WHERE key = 'gate') = 'off'
      AND NOT (SELECT rolcanlogin FROM pg_roles WHERE rolname = 'fixture_owner'),
    'seedProtected', EXISTS (SELECT FROM fixture_l1.state WHERE key = 'pinned' AND payload = 'version-1')),
  'protectedSha256', (SELECT encode(sha256(convert_to(string_agg(key || ':' || payload, ',' ORDER BY key), 'UTF8')), 'hex') FROM fixture_l1.state),
  'history', jsonb_build_object(
    'holdsExact', (SELECT bool_and(pinned) FROM fixture_l1.history),
    'historyRows', (SELECT count(*) FROM fixture_l1.history WHERE pinned),
    'historyTotal', (SELECT count(*) FROM fixture_l1.history),
    'historySha256', (SELECT encode(sha256(convert_to(jsonb_agg(to_jsonb(w) ORDER BY revision)::text, 'UTF8')), 'hex') FROM fixture_l1.history w),
    'outboxPending', (SELECT count(*) FROM fixture_l1.outbox WHERE pending AND attempts = 0),
    'outboxTotal', (SELECT count(*) FROM fixture_l1.outbox),
    'outboxSha256', (SELECT encode(sha256(convert_to(jsonb_agg(to_jsonb(w) ORDER BY event)::text, 'UTF8')), 'hex') FROM fixture_l1.outbox w)),
  'edge', jsonb_build_object(
    'absent', NOT EXISTS (SELECT FROM edge_ns), 'xid', (SELECT xid FROM edge_ns),
    'status', (SELECT pg_xact_status(xid::xid8) FROM edge_ns), 'owner', (SELECT owner FROM edge_ns),
    'consistentXid', EXISTS (SELECT FROM edge_ns e JOIN edge_rel t USING (xid) JOIN edge_fn f USING (xid)),
    'closes', NOT (SELECT rolcanlogin FROM pg_roles WHERE rolname = 'fixture_owner'),
    'rpcs', EXISTS (SELECT FROM edge_fn), 'storage', EXISTS (SELECT FROM edge_rel),
    'permissions', (SELECT NOT has_schema_privilege(current_user, oid, 'CREATE') FROM edge_ns)
      AND (SELECT NOT has_function_privilege(current_user, oid, 'EXECUTE') FROM edge_fn),
    'rls', (SELECT relrowsecurity AND relforcerowsecurity FROM edge_rel)));
COMMIT;
`;

test('reconciles PostgreSQL 17.12 catalog anchors and rejects post-commit closure or protection drift', { timeout: 60_000 }, t => {
  const root = mkdtempSync(join(realpathSync('/tmp'), 'ecv-s37-edge-'));
  const data = join(root, 'db');
  const port = '54846';
  let started = false;
  t.after(() => {
    if (started) pg('pg_ctl', ['-D', data, '-m', 'fast', '-w', 'stop']);
    rmSync(root, { recursive: true, force: true });
  });
  pg('initdb', ['-D', data, '-U', 'fixture_admin', '--no-locale', '--encoding=UTF8',
    '--auth-local=trust', '--auth-host=reject']);
  pg('pg_ctl', ['-D', data, '-l', join(root, 'server.log'), '-o',
    '-c listen_addresses= -k ' + root + ' -p ' + port, '-w', 'start']);
  started = true;

  const sql = (input, role = 'fixture_admin') => pg('psql', ['-XqAt', '--no-password', '-v', 'ON_ERROR_STOP=1',
    '-h', root, '-p', port, '-U', role, '-d', 'postgres'], input);
  sql(`
    BEGIN;
    CREATE ROLE fixture_observer LOGIN NOINHERIT;
    CREATE ROLE fixture_owner NOLOGIN NOINHERIT;
    CREATE SCHEMA fixture_l1;
    CREATE TABLE fixture_l1.runs (id integer, closed_at timestamptz);
    CREATE TABLE fixture_l1.owners (run integer);
    CREATE TABLE fixture_l1.state (key text, payload text);
    INSERT INTO fixture_l1.state VALUES ('gate', 'off'), ('pinned', 'version-1');
    CREATE TABLE fixture_l1.history (revision integer, pinned boolean);
    INSERT INTO fixture_l1.history VALUES (1, true);
    CREATE TABLE fixture_l1.outbox (event integer, pending boolean, attempts integer);
    INSERT INTO fixture_l1.outbox VALUES (1, true, 0);
    GRANT EXECUTE ON FUNCTION pg_control_system() TO fixture_observer;
    GRANT USAGE ON SCHEMA fixture_l1 TO fixture_observer;
    GRANT SELECT ON ALL TABLES IN SCHEMA fixture_l1 TO fixture_observer;
    COMMIT;
    BEGIN;
    CREATE UNIQUE INDEX only_open ON fixture_l1.runs ((1)) WHERE closed_at IS NULL;
    ALTER TABLE fixture_l1.owners ADD CONSTRAINT owner_once UNIQUE (run);
    COMMIT;
  `);

  const readback = () => JSON.parse(sql(observe, 'fixture_observer'));
  const before = readback();
  const install = `
    BEGIN;
    CREATE SCHEMA fixture_edge AUTHORIZATION fixture_owner;
    SET LOCAL ROLE fixture_owner;
    CREATE TABLE fixture_edge.files (id integer);
    ALTER TABLE fixture_edge.files ENABLE ROW LEVEL SECURITY;
    ALTER TABLE fixture_edge.files FORCE ROW LEVEL SECURITY;
    CREATE FUNCTION fixture_edge.read_file() RETURNS integer LANGUAGE sql AS 'SELECT 1';
    REVOKE EXECUTE ON FUNCTION fixture_edge.read_file() FROM PUBLIC;
    COMMIT;
  `;
  const plan = {
    identity: { ...before.identity, forwardXid: before.identity.forwardIndexXid },
    protection: { catalogSha256: before.protectedSha256, historySha256: before.history.historySha256,
      outboxSha256: before.history.outboxSha256, historyRows: 1, outboxRows: 1 },
    edgeOwner: 'fixture_owner',
    requestId: '40000000-0000-4000-8000-000000000004',
    sqlSha256: sha(install),
  };
  const recordedDispatch = { project: plan.identity.project, requestId: plan.requestId, sqlSha256: plan.sqlSha256 };
  const verdict = after => checkL1EdgeCatalogWitness(plan, { before, after, recordedDispatch }).status;

  assert.equal(verdict(readback()), 'UNKNOWN');
  sql(install);
  assert.equal(verdict(readback()), 'HISTORY_CATALOG_SHAPE_MATCH_ONLY');
  sql('GRANT EXECUTE ON FUNCTION fixture_edge.read_file() TO fixture_observer');
  assert.equal(verdict(readback()), 'UNKNOWN');
  sql('REVOKE EXECUTE ON FUNCTION fixture_edge.read_file() FROM fixture_observer');
  sql("UPDATE fixture_l1.state SET payload = 'on' WHERE key = 'gate'");
  assert.equal(verdict(readback()), 'NO_GO');
  sql("UPDATE fixture_l1.state SET payload = 'off' WHERE key = 'gate'; UPDATE fixture_l1.outbox SET attempts = 1");
  assert.equal(verdict(readback()), 'NO_GO');
});
